using System;

namespace uppgift4_1
{
    class Program
    {
      static void Main(string[] args)
      {
        for (int i = 10; i >= 1; i++)
        {
            Console.WriteLine(i);
        }

        for (int i = 200; i >= 100; i--)
        {
            Console.WriteLine(i);
        }

        for (int i = 1000; i <= 1400; i += 50)
        {
            Console.WriteLine(i);
        }
       }
  
    }

}
